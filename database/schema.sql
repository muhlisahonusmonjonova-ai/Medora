-- Core schema. Patient password_hash is nullable to support the public,
-- passwordless booking form; authenticated patient accounts can set it later.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(32) NOT NULL UNIQUE,
    password_hash TEXT,
    role VARCHAR(16) NOT NULL CHECK (role IN ('patient', 'doctor', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS doctors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    specialty VARCHAR(120) NOT NULL,
    experience_years INTEGER NOT NULL DEFAULT 0 CHECK (experience_years >= 0),
    price_per_visit NUMERIC(10, 2) NOT NULL CHECK (price_per_visit >= 0),
    photo_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Keep an existing installation compatible when applying this schema again.
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS photo_url TEXT;
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE CASCADE,
    available_date DATE NOT NULL,
    available_time TIME NOT NULL,
    is_booked BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (doctor_id, available_date, available_time)
);

CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE RESTRICT,
    schedule_id BIGINT NOT NULL UNIQUE REFERENCES schedules(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS schedules_available_doctor_date_idx
    ON schedules (doctor_id, available_date, available_time)
    WHERE is_booked = FALSE;

CREATE INDEX IF NOT EXISTS doctors_active_specialty_idx
    ON doctors (specialty) WHERE is_active = TRUE;
CREATE INDEX IF NOT EXISTS appointments_patient_id_idx ON appointments (patient_id);
CREATE INDEX IF NOT EXISTS appointments_doctor_id_idx ON appointments (doctor_id);
